#!/usr/bin/env python3
"""Phase 5 report: results/endterm/phase5/phase5_summary.md from
results/endterm/phase5/all_runs_metrics.csv (run phase5_metrics.py first).

Curated tables of the per-run metrics; every value is read from the CSV.
"""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
P5 = ROOT / "results" / "endterm" / "phase5"


def load():
    rows = []
    for r in csv.DictReader(open(P5 / "all_runs_metrics.csv")):
        for k, v in list(r.items()):
            if v in ("", "None"):
                r[k] = None
            elif k not in ("phase", "group", "input", "kernel", "l1d_prefetcher"):
                try:
                    r[k] = float(v)
                except ValueError:
                    pass
        r["valid"] = r["valid"] == "True"
        rows.append(r)
    return rows


def one(rows, **kw):
    for r in rows:
        if r["valid"] and all(r.get(k) == v for k, v in kw.items()):
            return r
    return None


def f(v, kind=""):
    if v is None:
        return "–"
    if kind == "x":
        return f"{v:.2f}×"
    if kind == "pct":
        return f"{v * 100:.1f}%"
    if kind == "mib":
        return f"{v / 2**20:,.2f}"
    if kind == "k":
        return f"{v / 1000:,.1f}k"
    if abs(v) >= 1000:
        return f"{v:,.0f}"
    return f"{v:.3g}"


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---:" if i else "---" for i in range(len(header))) + "|"]
    return out + ["| " + " | ".join(r) + " |" for r in rows]


def main():
    rows = load()
    valid = sum(r["valid"] for r in rows)
    md = ["# Phase 5: metrics, analysis and figures", "",
          f"Source: `results/endterm/phase5/all_runs_metrics.csv`, one row per run, **{len(rows)} runs, {valid} validated** "
          "(the failed ones are the LMUL ≥ 2 gather kernels hit by gem5 Issue 2 and are excluded everywhere). Generated by "
          "`scripts/phase5_metrics.py`; this file by `scripts/phase5_report.py`; figures by `scripts/phase5_plots.py`.", "",
          "## Metric definitions", "",
          "| Metric | Definition |", "|---|---|",
          "| ROI time | kernel-only cycles (gem5 `numCycles` between the ROI markers); 1 GHz clock, so µs = cycles / 1000 |",
          "| Speedup vs. scalar / vs. RVV baseline | ROI cycles of `scalar` / `rvv_orig` ÷ ROI cycles of the kernel: same input, same phase (same binaries), same VLEN and same L1D prefetcher |",
          "| Lane utilisation | active elements ÷ (vector chunks × VLMAX) of the multiply-accumulate, computed by the program from the matrix |",
          "| L1D miss rate (raw / primary) | gem5 `demandMisses / demandAccesses` (raw counts accesses merging into an in-flight miss); primary = `demandMshrMisses / demandAccesses` |",
          "| MPKI | misses per 1000 committed instructions (ROI) |",
          "| DRAM traffic / bandwidth | `bytesReadSys` (+ `bytesWrittenSys`) in the ROI; bandwidth = bytes ÷ ROI time |",
          "| Useful vs. skipped work (Phase 4A) | `WORK` line: lanes issued to arithmetic, useful lanes (= nonzeros), zero lanes, all-zero chunks skipped |",
          "| LQ-full stalls | gem5 `rename.LQFullEvents` in the ROI |",
          "| Prefetch accuracy / coverage | gem5 L1D prefetcher `accuracy`, `coverage` (Phase 4B) |", "",
          "## Figures (`results/endterm/phase5/figures/*.{pdf,png}`; plotted data in `figure_data/*.csv`)", "",
          "| Figure | Shows |", "|---|---|",
          "| `speedup_vs_density` | RVV CSR kernels and dense RVV GEMV vs. scalar CSR across density (Phase 3) |",
          "| `dense_vs_sparse_crossover` | CSR vs. dense kernel time, interpolated crossover, density-aware hybrid (Phase 4A, same binary) |",
          "| `lane_util_vs_row_length` | lane utilisation of the RVV CSR kernel vs. mean row length (synthetic + SuiteSparse) |",
          "| `vip_speedup` | VIP speedup over the stride prefetcher, four kernels, 11 inputs (Phase 4B) |",
          "| `vip_memory_behaviour` | L1D primary miss rate, DRAM read traffic, LQ-full stalls with and without VIP (Phase 4B) |",
          "| `vlen_sensitivity` | VLEN 128/256/512 for three inputs (Phase 3) |",
          "| `lmul_sensitivity_dense` | dense GEMV at LMUL 1/2/4 (LMUL>1 sparse gathers excluded: gem5 Issue 2) |",
          "| `vip_history_depth` | VIP speedup vs. history depth (Phase 4B follow-up; present once that batch has run) |", ""]

    # A. density sweep (Phase 3)
    md += ["## A. Speedup and lane utilisation vs. density (uniform 1024×1024, VLEN=256, Phase 3)", ""]
    t = []
    for d in (1, 5, 20, 50, 80):
        inp = f"u_n1024_d{d:02d}"
        o, dn, sc = (one(rows, phase="phase3", group="density", input=inp, kernel=k, vlen=256.0)
                     for k in ("rvv_orig", "dense_m2", "scalar"))
        t.append([f"{d}%", f(o and o["row_len_mean"]), f(sc and sc["roi_cycles"]), f(o and o["roi_cycles"]),
                  f(o and o["speedup_vs_scalar"], "x"), f(o and o["lane_util"], "pct"), f(o and o["roi_ipc"]),
                  f(dn and dn["roi_cycles"]), f(dn and dn["speedup_vs_scalar"], "x")])
    md += table(["density", "mean row", "scalar cycles", "RVV CSR cycles", "RVV CSR vs scalar", "lane util",
                 "RVV CSR IPC", "dense GEMV cycles", "dense vs scalar"], t)

    # B. memory vs working set (Phase 3 size sweep)
    md += ["", "## B. Memory behaviour vs. working-set size (16,384 rows × 16 nnz/row, uniform, `rvv_orig`, Phase 3)", ""]
    t = []
    for c in ("002048", "008192", "032768", "131072", "524288"):
        r = one(rows, phase="phase3", group="size", input=f"u_r16384_c{c}_npr16", kernel="rvv_orig")
        if r:
            t.append([f"{int(r['x_bytes']) // 1024} KiB", f(r["roi_cycles"]), f(r["speedup_vs_scalar"], "x"),
                      f(r["l1d_primary_miss_rate"], "pct"), f(r["l1d_mpki"]), f(r["l2_miss_rate"], "pct"),
                      f(r["l2_mpki"]), f(r["dram_bytes_read"], "mib"), f(r["dram_bw_gbs"]), f(r["lq_full_events"], "k")])
    md += table(["x size", "cycles", "vs scalar", "L1D primary miss", "L1D MPKI", "L2 miss", "L2 MPKI",
                 "DRAM read (MiB)", "DRAM BW (GB/s)", "LQ-full"], t)

    # C. useful vs skipped (Phase 4A)
    md += ["", "## C. Useful vs. skipped work of the Phase 4A mechanisms (uniform 1024×1024)", ""]
    t = []
    for d in (5, 20, 50):
        inp = f"u_n1024_d{d:02d}"
        for k in ("dense_m1", "dense_skip_m1", "dense_compress_m1", "rvv_orig", "hybrid"):
            r = one(rows, phase="phase4a", group="density", input=inp, kernel=k)
            if not r:
                continue
            skipped = (r["work_skipped_chunks"] / r["work_scanned_chunks"]) if r["work_scanned_chunks"] else None
            useful = (r["work_useful_lanes"] / r["work_arith_lanes"]) if r["work_arith_lanes"] else None
            t.append([f"{d}%", k, f(r["roi_cycles"]), f(r["speedup_vs_rvv_orig"], "x"), f(r["work_arith_lanes"]),
                      f(r["work_useful_lanes"]), f(r["work_zero_lanes"]), f(useful, "pct"), f(skipped, "pct")])
    md += table(["density", "kernel", "cycles", "vs RVV CSR", "lanes issued", "useful lanes", "zero lanes",
                 "useful fraction", "chunks skipped / scanned"], t)
    md += ["", "\"Chunks skipped\" = scanned vector chunks that issue no multiply-accumulate. For `dense_skip_m1` "
           "these are all-zero chunks; for `dense_compress_m1` the arithmetic runs once per packed full vector, so "
           "most scanned chunks issue none. CSR kernels never scan zeros."]

    # D. VIP on/off (Phase 4B)
    md += ["", "## D. Vector-Indirect Prefetcher on/off (`rvv_orig`, Phase 4B; stride → VIP)", ""]
    t = []
    for g, inp in [("size", f"u_r16384_c{c}_npr16") for c in ("008192", "032768", "131072", "524288")] + \
                  [("size", "p_r16384_c131072_npr16"), ("size", "p_r16384_c524288_npr16")] + \
                  [("suitesparse", m) for m in ("bcsstk17", "scircuit", "web-NotreDame", "luxembourg_osm")]:
        a = one(rows, phase="phase4b", group=g, input=inp, kernel="rvv_orig", l1d_prefetcher="stride")
        b = one(rows, phase="phase4b", group=g, input=inp, kernel="rvv_orig", l1d_prefetcher="vip")
        if not (a and b):
            continue
        pair = lambda k, kind="": f"{f(a[k], kind)} → {f(b[k], kind)}"  # noqa: E731
        t.append([inp, f(a["roi_cycles"] / b["roi_cycles"], "x"), pair("l1d_primary_miss_rate", "pct"),
                  pair("l2_miss_rate", "pct"), pair("dram_bytes_read", "mib"), pair("dram_bw_gbs"),
                  pair("lq_full_events", "k"), pair("pf_l1d_accuracy", "pct"), pair("pf_l1d_coverage", "pct")])
    md += table(["input", "speedup", "L1D primary miss", "L2 miss", "DRAM read (MiB)", "DRAM BW (GB/s)",
                 "LQ-full", "pf accuracy", "pf coverage"], t)

    # E. follow-up studies (if present)
    hist = [r for r in rows if r["phase"] == "phase4b" and r["group"] == "history" and r["valid"]]
    if hist:
        md += ["", "## E. VIP history depth (speedup over stride; Phase 4B follow-up)", ""]
        t = []
        for inp in sorted({r["input"] for r in hist}):
            for k in ("rvv_orig", "rvv_opt_m1", "rvv_acc2_m1"):
                s = one(rows, phase="phase4b", group="size", input=inp, kernel=k, l1d_prefetcher="stride")
                cells = []
                for h in (4, 8, 16, 32, 64, 128):
                    r = one(rows, phase="phase4b", group="history", input=inp, kernel=k, l1d_prefetcher=f"vip_h{h}")
                    cells.append(f(s["roi_cycles"] / r["roi_cycles"], "x") if r and s else "–")
                t.append([inp, k] + cells)
        md += table(["input", "kernel", "4", "8", "16", "32 (default)", "64", "128"], t)
    mshr = [r for r in rows if r["phase"] == "phase4b" and r["group"] == "mshr" and r["valid"]]
    if mshr:
        md += ["", "## F. L1D MSHRs (VIP speedup over stride at the same MSHR count; Phase 4B follow-up)", ""]
        t = []
        for inp in sorted({r["input"] for r in mshr}):
            for k in ("rvv_orig", "rvv_acc2_m1"):
                cells = []
                for m in (16, 32, 64):
                    grp, cs, cv = ("size", "stride", "vip") if m == 16 else ("mshr", f"stride_mshr{m}", f"vip_mshr{m}")
                    s = one(rows, phase="phase4b", group=grp, input=inp, kernel=k, l1d_prefetcher=cs)
                    v = one(rows, phase="phase4b", group=grp, input=inp, kernel=k, l1d_prefetcher=cv)
                    cells.append(f"{f(s and s['roi_cycles'])} / {f(v and v['roi_cycles'])} "
                                 f"({f(s['roi_cycles'] / v['roi_cycles'], 'x') if s and v else '–'})")
                t.append([inp, k] + cells)
        md += table(["input", "kernel", "16 MSHRs: stride / VIP", "32 MSHRs", "64 MSHRs"], t)

    md += ["", "Note on figure colours: the reference categorical palette (slots 1–6, documented order) is used with one "
           "colour per entity across all figures. Its colour-blind/contrast validator could not be run here (no Node.js "
           "on the host or in the container); the documented order is used unchanged, lines carry direct labels and "
           "every figure has its data table in `figure_data/`."]
    (P5 / "phase5_summary.md").write_text("\n".join(md) + "\n")
    print(f"wrote {P5 / 'phase5_summary.md'}")


if __name__ == "__main__":
    main()
